
-- STUDENT ERP DATABASE SCHEMA
-- Execute in Oracle APEX SQL Workshop > SQL Commands.

CREATE TABLE APP_USERS (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    username VARCHAR2(100) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    role VARCHAR2(20) NOT NULL,
    is_active CHAR(1) DEFAULT 'Y' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_app_users_role
        CHECK (role IN ('ADMIN', 'STAFF', 'STUDENT')),
    CONSTRAINT chk_app_users_active
        CHECK (is_active IN ('Y', 'N'))
);

CREATE TABLE STUDENTS (
    student_id NUMBER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    user_id NUMBER UNIQUE,
    register_number VARCHAR2(30) NOT NULL UNIQUE,
    full_name VARCHAR2(150) NOT NULL,
    email VARCHAR2(150),
    class_name VARCHAR2(50) NOT NULL,
    section VARCHAR2(10),
    CONSTRAINT fk_students_user
        FOREIGN KEY (user_id) REFERENCES APP_USERS(user_id)
);

CREATE TABLE STAFF (
    staff_id NUMBER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    user_id NUMBER UNIQUE,
    staff_code VARCHAR2(30) NOT NULL UNIQUE,
    full_name VARCHAR2(150) NOT NULL,
    email VARCHAR2(150),
    CONSTRAINT fk_staff_user
        FOREIGN KEY (user_id) REFERENCES APP_USERS(user_id)
);

CREATE TABLE SUBJECTS (
    subject_id NUMBER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    subject_code VARCHAR2(30) NOT NULL UNIQUE,
    subject_name VARCHAR2(100) NOT NULL
);

CREATE TABLE ATTENDANCE (
    attendance_id NUMBER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    student_id NUMBER NOT NULL,
    subject_id NUMBER NOT NULL,
    marked_by_staff_id NUMBER NOT NULL,
    attendance_date DATE NOT NULL,
    status VARCHAR2(10) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_att_student
        FOREIGN KEY (student_id) REFERENCES STUDENTS(student_id),
    CONSTRAINT fk_att_subject
        FOREIGN KEY (subject_id) REFERENCES SUBJECTS(subject_id),
    CONSTRAINT fk_att_staff
        FOREIGN KEY (marked_by_staff_id) REFERENCES STAFF(staff_id),
    CONSTRAINT chk_att_status
        CHECK (status IN ('PRESENT', 'ABSENT')),
    CONSTRAINT uq_attendance_entry
        UNIQUE (student_id, subject_id, attendance_date)
);

CREATE TABLE MARKS (
    mark_id NUMBER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    student_id NUMBER NOT NULL,
    subject_id NUMBER NOT NULL,
    exam_name VARCHAR2(100) NOT NULL,
    marks_obtained NUMBER(6,2) NOT NULL,
    max_marks NUMBER(6,2) NOT NULL,
    entered_by_staff_id NUMBER NOT NULL,
    CONSTRAINT fk_marks_student
        FOREIGN KEY (student_id) REFERENCES STUDENTS(student_id),
    CONSTRAINT fk_marks_subject
        FOREIGN KEY (subject_id) REFERENCES SUBJECTS(subject_id),
    CONSTRAINT fk_marks_staff
        FOREIGN KEY (entered_by_staff_id) REFERENCES STAFF(staff_id),
    CONSTRAINT chk_marks_range
        CHECK (
            marks_obtained >= 0
            AND max_marks > 0
            AND marks_obtained <= max_marks
        ),
    CONSTRAINT uq_student_exam
        UNIQUE (student_id, subject_id, exam_name)
);

CREATE TABLE TIMETABLE (
    timetable_id NUMBER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    class_name VARCHAR2(50) NOT NULL,
    section VARCHAR2(10),
    subject_id NUMBER NOT NULL,
    staff_id NUMBER NOT NULL,
    day_of_week VARCHAR2(10) NOT NULL,
    start_time VARCHAR2(5) NOT NULL,
    end_time VARCHAR2(5) NOT NULL,
    CONSTRAINT fk_tt_subject
        FOREIGN KEY (subject_id) REFERENCES SUBJECTS(subject_id),
    CONSTRAINT fk_tt_staff
        FOREIGN KEY (staff_id) REFERENCES STAFF(staff_id),
    CONSTRAINT chk_tt_day
        CHECK (
            day_of_week IN (
                'MONDAY', 'TUESDAY', 'WEDNESDAY',
                'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY'
            )
        )
);

CREATE TABLE ANNOUNCEMENTS (
    announcement_id NUMBER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    title VARCHAR2(200) NOT NULL,
    message VARCHAR2(2000) NOT NULL,
    created_by_user_id NUMBER NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_announcement_user
        FOREIGN KEY (created_by_user_id)
        REFERENCES APP_USERS(user_id)
);
